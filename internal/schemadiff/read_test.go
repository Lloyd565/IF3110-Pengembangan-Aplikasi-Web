func fixtureStatements(kind dbconn.DBMS, schema string, desired bool) []string {
	q := func(name string) string { return qualified(kind, schema, name) }
	id := "INTEGER GENERATED BY DEFAULT AS IDENTITY"
	if kind == dbconn.MariaDB {
		id = "INT AUTO_INCREMENT"
	}
	label := "VARCHAR(20) NOT NULL DEFAULT 'old', obsolete TEXT"
	if desired {
		label = "VARCHAR(80) NOT NULL DEFAULT 'new', flag INT NOT NULL DEFAULT 0"
	}
	out := []string{"CREATE TABLE " + q("parents") + "(id " + id + " PRIMARY KEY, label " + label + ", CONSTRAINT label_nonempty CHECK(char_length(label)>0))",
		"CREATE TABLE " + q("children") + "(id INT PRIMARY KEY, parent_id INT, CONSTRAINT fk_children_parent FOREIGN KEY(parent_id) REFERENCES " + q("parents") + "(id) ON DELETE CASCADE)"}
	if desired {
		out = append(out, "CREATE TABLE "+q("added")+"(id "+id+" PRIMARY KEY, parent_id INT, note TEXT, CONSTRAINT fk_added_parent FOREIGN KEY(parent_id) REFERENCES "+q("parents")+"(id))", "CREATE INDEX label_idx ON "+q("parents")+"(label DESC)")
	} else {
		out = append(out, "CREATE TABLE "+q("removed")+"(id INT PRIMARY KEY)", "CREATE INDEX old_idx ON "+q("parents")+"(label)")
	}
	return out
}

func checkPlanRoundTrip(t *testing.T, current, reference *dbconn.Target, schema, refSchema string, execute func(string) error) {
	t.Helper()
	ctx := context.Background()
	before, err := Read(ctx, current, schema)
	if err != nil {
		t.Fatal(err)
	}
	desired, err := Read(ctx, reference, refSchema)
	if err != nil {
		t.Fatal(err)
	}
	p, err := Compare(before, desired)
	if err != nil || len(p.Steps) == 0 || len(p.Manual) > 0 {
		t.Fatalf("plan err=%v manual=%v changes=%+v", err, p.Manual, p.Changes)
	}
	for _, step := range p.Steps {
		if err := execute(step.SQL); err != nil {
			t.Fatalf("generated DDL failed: %s\n%v", step.SQL, err)
		}
	}
	after, err := Read(ctx, current, schema)
	if err != nil {
		t.Fatal(err)
	}
	remaining, err := Compare(after, desired)
	if err != nil || len(remaining.Changes) != 0 {
		t.Fatalf("schema did not converge: %+v manual=%v err=%v", remaining.Changes, remaining.Manual, err)
	}
	if before.Fingerprint() == after.Fingerprint() {
		t.Fatal("fingerprint failed to detect structural changes")
	}
}

func TestIntegrationPostgresRoundTrip(t *testing.T) {
	db := testdb.Fresh(t, "schemadiff_pg")
	ctx := context.Background()
	if _, err := db.Exec(ctx, "CREATE SCHEMA live;CREATE SCHEMA reference"); err != nil {
		t.Fatal(err)
	}
	for _, entry := range []struct {
		schema  string
		desired bool
	}{{"live", false}, {"reference", true}} {
		for _, q := range fixtureStatements(dbconn.PostgreSQL, entry.schema, entry.desired) {
			if _, err := db.Exec(ctx, q); err != nil {
				t.Fatal(q, err)
			}
		}
	}
	if _, err := db.Exec(ctx, `INSERT INTO live.parents(label) VALUES('keep'); INSERT INTO live.children VALUES(1,1)`); err != nil {
		t.Fatal(err)
	}
	target := &dbconn.Target{DBMS: dbconn.PostgreSQL, Postgres: db}
	checkPlanRoundTrip(t, target, target, "live", "reference", func(q string) error { _, err := db.Exec(ctx, q); return err })
	var label string
	if err := db.QueryRow(ctx, "SELECT label FROM live.parents WHERE id=1").Scan(&label); err != nil || label != "keep" {
		t.Fatal("existing data lost", err)
	}
	if _, err := Read(ctx, target, "pg_catalog"); err == nil {
		t.Fatal("system schema accepted")
	}
}

func TestIntegrationMariaRoundTrip(t *testing.T) {
	cur, name := testdb.FreshMaria(t, "schemadiff_maria_current")
	ref, refName := testdb.FreshMaria(t, "schemadiff_maria_ref")
	ctx := context.Background()
	for _, entry := range []struct {
		target  *dbconn.Target
		desired bool
	}{{&dbconn.Target{DBMS: dbconn.MariaDB, Database: name, Maria: cur}, false}, {&dbconn.Target{DBMS: dbconn.MariaDB, Database: refName, Maria: ref}, true}} {
		for _, q := range fixtureStatements(dbconn.MariaDB, entry.target.Database, entry.desired) {
			if _, err := entry.target.Maria.ExecContext(ctx, q); err != nil {
				t.Fatal(q, err)
			}
		}
	}
	if _, err := cur.ExecContext(ctx, fmt.Sprintf("INSERT INTO %s(label) VALUES('keep')", qualified(dbconn.MariaDB, name, "parents"))); err != nil {
		t.Fatal(err)
	}
	if _, err := cur.ExecContext(ctx, `ALTER TABLE parents MODIFY label VARCHAR(20) NOT NULL DEFAULT 'old' COMMENT 'retain this comment'`); err != nil {
		t.Fatal(err)
	}
	current := &dbconn.Target{DBMS: dbconn.MariaDB, Database: name, Maria: cur}
	desired := &dbconn.Target{DBMS: dbconn.MariaDB, Database: refName, Maria: ref}
	checkPlanRoundTrip(t, current, desired, name, refName, func(q string) error { _, err := cur.ExecContext(ctx, q); return err })
	var label string
	if err := cur.QueryRowContext(ctx, "SELECT label FROM parents WHERE id=1").Scan(&label); err != nil || label != "keep" {
		t.Fatal("existing data lost", err)
	}
	var comment string
	if err := cur.QueryRowContext(ctx, `SELECT COLUMN_COMMENT FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=? AND TABLE_NAME='parents' AND COLUMN_NAME='label'`, name).Scan(&comment); err != nil || comment != "retain this comment" {
		t.Fatal("MODIFY removed an existing column comment", err)
	}
	if _, err := Read(ctx, current, "mysql"); err == nil {
		t.Fatal("cross-database snapshot accepted")
	}
}

func TestIntegrationPostgresSerialAndAdvancedMetadata(t *testing.T) {
	db := testdb.Fresh(t, "diff_pg_advanced")
	ctx := context.Background()
	target := &dbconn.Target{DBMS: dbconn.PostgreSQL, Postgres: db}
	if _, err := db.Exec(ctx, `CREATE SCHEMA live;CREATE SCHEMA reference;
		CREATE TABLE reference.serial_table(id SERIAL PRIMARY KEY,note TEXT);
		CREATE UNIQUE INDEX nullable_idx ON reference.serial_table(note) INCLUDE(id) NULLS NOT DISTINCT`); err != nil {
		t.Fatal(err)
	}
	checkPlanRoundTrip(t, target, target, "live", "reference", func(q string) error { _, err := db.Exec(ctx, q); return err })
	before, err := Read(ctx, target, "live")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(ctx, "INSERT INTO live.serial_table(note) VALUES('preserve')"); err != nil {
		t.Fatal(err)
	}
	after, err := Read(ctx, target, "live")
	if err != nil || before.Fingerprint() != after.Fingerprint() {
		t.Fatal("data/sequence counter changed schema fingerprint", err)
	}
	if _, err := db.Exec(ctx, "CREATE INDEX expr_idx ON reference.serial_table(lower(note))"); err != nil {
		t.Fatal(err)
	}
	first, err := Read(ctx, target, "reference")
	if err != nil {
		t.Fatal(err)
	}
	plan, err := Compare(after, first)
	if err != nil || len(plan.Manual) == 0 || len(plan.Steps) != 0 {
		t.Fatal("expression index silently generated", err)
	}
	if _, err := db.Exec(ctx, "DROP INDEX reference.expr_idx; CREATE INDEX expr_idx ON reference.serial_table(upper(note))"); err != nil {
		t.Fatal(err)
	}
	second, err := Read(ctx, target, "reference")
	if err != nil || first.Fingerprint() == second.Fingerprint() {
		t.Fatal("expression index changes were not captured", err)
	}
	if _, err := db.Exec(ctx, "CREATE INDEX pattern_idx ON reference.serial_table(note text_pattern_ops); ALTER SEQUENCE reference.serial_table_id_seq MAXVALUE 1000"); err != nil {
		t.Fatal(err)
	}
	advanced, err := Read(ctx, target, "reference")
	if err != nil {
		t.Fatal(err)
	}
	plan, err = Compare(after, advanced)
	if err != nil || len(plan.Manual) == 0 || len(plan.Steps) != 0 || advanced.Tables[0].Columns[0].Manual == "" {
		t.Fatal("custom sequence/operator class not blocked", err)
	}
}
